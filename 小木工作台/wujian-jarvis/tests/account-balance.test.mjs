test('失败事务回滚，不留半条余额或审计',()=>{
 const a=create(),before=w.listBalanceChanges(a.id);
 db.exec("CREATE TRIGGER test_fail BEFORE INSERT ON operation_events BEGIN SELECT RAISE(ABORT,'test failure'); END");
 assert.throws(()=>w.syncAccountBalance(a.id,{balance:1200000}),/test failure/);
 db.exec('DROP TRIGGER test_fail');
 assert.equal(get(a.id).equity,1100000);assert.deepEqual(w.listBalanceChanges(a.id),before);
});
