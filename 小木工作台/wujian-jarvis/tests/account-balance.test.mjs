test('错误余额作废、修正任意历史、备注审计，绝不覆盖后续绝对余额',()=>{
 const wrong=w.syncAccountBalance(first.id,{balance:9900000,sourcePage:'测试'});
 assert.throws(()=>w.voidBalance(first.id,wrong.change.id,{reason:'误录'}),/确认/);
 w.voidBalance(first.id,wrong.change.id,{confirmed:true,reason:'误录'});
 assert.equal(get(first.id).equity,1080000);assert.equal(w.listBalanceChanges(first.id)[0].status,'已作废');
 const earlier=w.listBalanceChanges(first.id).find(c=>c.afterBalance===1110000);
 w.editBalanceChange(first.id,earlier.id,{balance:1115000,note:'改正历史值'});
 assert.equal(get(first.id).equity,1080000);
 w.editBalanceChange(first.id,earlier.id,{action:'note',note:'再次核对备注'});
 assert.equal(get(first.id).equity,1080000);
 assert.equal(db.prepare('SELECT count(*) AS n FROM balance_audit WHERE change_id=?').get(earlier.id).n,2);
 assert.match(db.prepare('SELECT before_json FROM balance_audit WHERE change_id=? ORDER BY rowid LIMIT 1').get(earlier.id).before_json,/1110000/);
 assert.throws(()=>w.editBalanceChange(second.id,earlier.id,{balance:1}),/不属于/);
 assert.throws(()=>w.voidBalance(second.id,earlier.id,{confirmed:true,reason:'误操作'}),/不属于/);
});
